//! `export_cpa` over a hand-written catalog: what becomes a `models[]` item, what is skipped and why.

use serde_json::{Value, json};
use tierbridge_catalog::{
    CatalogError,
    export_cpa::{CpaOptions, PLACEHOLDER_KEY, SkipReason, export_cpa},
};

fn row(gateway: &str, provider: &str, id: &str, extra: Value) -> Value {
    let mut row = json!({
        "recordType": "model",
        "key": format!("{gateway}:{provider}/{id}"),
        "provider": provider,
        "id": id,
        "name": id,
        "kind": "chat",
        "contextWindow": null,
        "input": null,
        "output": null,
        "thinking": null,
        "lifecycle": null,
    });
    row.as_object_mut()
        .unwrap()
        .extend(extra.as_object().unwrap().clone());
    row
}

fn options(gateway: &str) -> CpaOptions<'_> {
    CpaOptions {
        gateway,
        provider_name: "tb-gw",
        base_url: "http://127.0.0.1:8317/v1",
        api_key: None,
        alias_prefix: "tb-",
        model_prefix: None,
    }
}

fn run(rows: &[Value], opts: &CpaOptions<'_>) -> tierbridge_catalog::export_cpa::CpaExport {
    export_cpa(&serde_json::to_vec(rows).unwrap(), opts).unwrap()
}

#[test]
fn emits_the_v8_block_with_limits_modalities_and_thinking_levels() {
    let rows = [
        row(
            "omp-live:gw",
            "gw",
            "big",
            json!({
                "name": "Big Model",
                "contextWindow": 262144,
                "input": ["text", "image"],
                "output": ["text"],
                "thinking": {"mode": "effort", "efforts": ["off", "high", "low", "high"]},
                "lifecycle": {"status": "live", "replacement": null, "shutdownOn": null},
            }),
        ),
        row("omp-live:gw", "gw", "plain", json!({})),
    ];
    let out = run(&rows, &options("omp-live:gw"));
    let expected = format!(
        r#"# Generated by `tierbridge export cpa` from gateway "omp-live:gw" (2 models). Do not edit by hand.
# Goes under the `api-keys:` root of a config-version 8 CLIProxyAPI config.
api-keys:
  openai-compatibility:
    - name: "tb-gw"
      base-url: "http://127.0.0.1:8317/v1"
      keys:
        - api-key: "{PLACEHOLDER_KEY}"
      models:
        - name: "big"
          alias: "tb-big"
          display-name: "Big Model"
          max-context-length: 262144
          input-modalities: [text, image]
          output-modalities: [text]
          thinking:
            levels: ["low", "high"]
        - name: "plain"
          alias: "tb-plain"
"#
    );
    assert_eq!(out.yaml, expected);
    assert!(out.skipped.is_empty());
}

#[test]
fn key_and_prefix_are_written_when_given() {
    let rows = [row("gw", "p", "m", json!({}))];
    let out = run(
        &rows,
        &CpaOptions {
            api_key: Some("sk-\"quoted\""),
            model_prefix: Some("free"),
            ..options("gw")
        },
    );
    assert!(out.yaml.contains("      prefix: \"free\"\n      base-url:"));
    assert!(out.yaml.contains(r#"- api-key: "sk-\"quoted\"""#));
    assert!(!out.yaml.contains(PLACEHOLDER_KEY));
}

#[test]
fn skips_non_chat_retired_and_duplicate_aliases_and_other_gateways() {
    let rows = [
        row("gw", "p", "embed", json!({"kind": "embedding"})),
        row(
            "gw",
            "p",
            "gone",
            json!({"lifecycle": {"status": "retired", "replacement": null, "shutdownOn": null}}),
        ),
        row(
            "gw",
            "p",
            "old",
            json!({"lifecycle": {"status": "deprecated", "replacement": null, "shutdownOn": null}}),
        ),
        row("gw", "a", "same", json!({})),
        row("gw", "b", "same", json!({})),
        row("other", "p", "elsewhere", json!({})),
        // no kind recorded: kept, a gateway row without a kind is assumed to be chat
        row("gw", "p", "unkinded", json!({"kind": null})),
    ];
    let out = run(&rows, &options("gw"));
    let aliases: Vec<&str> = out.models.iter().map(|m| m.alias.as_str()).collect();
    assert_eq!(aliases, ["tb-old", "tb-same", "tb-unkinded"]);
    assert_eq!(
        out.skipped,
        [
            ("gw:b/same".to_owned(), SkipReason::DuplicateAlias),
            ("gw:p/embed".to_owned(), SkipReason::NotChat),
            ("gw:p/gone".to_owned(), SkipReason::Retired),
        ]
    );
}

#[test]
fn ids_with_slashes_and_colons_survive_quoting_and_the_gateway_id_may_contain_a_colon() {
    let rows = [row(
        "omp-live:gw",
        "gw",
        "moonshotai/kimi-k2:free",
        json!({}),
    )];
    let out = run(&rows, &options("omp-live:gw"));
    assert_eq!(out.models[0].name, "moonshotai/kimi-k2:free");
    assert!(out.yaml.contains("alias: \"tb-moonshotai/kimi-k2:free\""));
}

#[test]
fn toggle_and_unknown_thinking_emit_no_levels() {
    let rows = [
        row(
            "gw",
            "p",
            "t",
            json!({"thinking": {"mode": "toggle", "efforts": []}}),
        ),
        row(
            "gw",
            "p",
            "e",
            json!({"thinking": {"mode": "effort", "efforts": ["off"]}}),
        ),
    ];
    let out = run(&rows, &options("gw"));
    assert!(!out.yaml.contains("thinking:"), "{}", out.yaml);
}

#[test]
fn output_is_deterministic_regardless_of_row_order() {
    let a = row("gw", "p", "a", json!({"contextWindow": 1000}));
    let b = row("gw", "p", "b", json!({}));
    let forward = run(&[a.clone(), b.clone()], &options("gw")).yaml;
    let backward = run(&[b, a], &options("gw")).yaml;
    assert_eq!(forward, backward);
}

#[test]
fn unknown_gateway_lists_the_ones_present() {
    let rows = [
        row("one", "p", "m", json!({})),
        row("two:x", "p", "m", json!({})),
    ];
    let err = export_cpa(&serde_json::to_vec(&rows).unwrap(), &options("three")).unwrap_err();
    let CatalogError::Export(message) = &err else {
        panic!("{err:?}")
    };
    assert!(message.contains("one, two:x"), "{message}");
}

#[test]
fn a_catalog_that_is_not_json_fails() {
    assert!(matches!(
        export_cpa(b"[{\"key\":", &options("gw")),
        Err(CatalogError::InvalidJson(_))
    ));
}
