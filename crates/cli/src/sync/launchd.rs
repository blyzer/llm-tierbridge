//! `tierbridge sync install-launchd` / `uninstall-launchd`: a daily launchd job that runs a wrapper,
//! which loads the secrets omp discovery needs from the macOS Keychain (launchd jobs inherit no
//! environment) and then `exec`s `tierbridge sync run`.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use clap::Args;

use super::fetch;
use super::state::STATE_FILE;
use crate::{Failure, failure};

pub const LABEL: &str = "dev.blyzer.llm-tierbridge.sync";
/// Keychain service every secret is stored under (`-s`); the variable name is the account (`-a`).
pub const KEYCHAIN_SERVICE: &str = "llm-tierbridge";
const DEFAULT_KEYCHAIN_VAR: &str = "EASYCLIPROXY_API_KEY";
/// What launchd jobs get instead of the user's PATH: Homebrew (git, gh, node) and the system.
const JOB_PATH: &str = "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin";

#[derive(Args)]
pub struct InstallArgs {
    /// The private data repo the job syncs.
    #[arg(long, value_name = "DIR")]
    data_repo: PathBuf,
    /// Hour of the daily run (local time).
    #[arg(long, default_value_t = 6, value_parser = clap::value_parser!(u8).range(0..=23))]
    hour: u8,
    /// Minute of the daily run.
    #[arg(long, default_value_t = 0, value_parser = clap::value_parser!(u8).range(0..=59))]
    minute: u8,
    /// Variable the wrapper loads from the Keychain before the run (repeatable). Each is read with
    /// `security find-generic-password -s llm-tierbridge -a <VAR> -w`.
    #[arg(long = "keychain-var", value_name = "VAR", default_values_t = [DEFAULT_KEYCHAIN_VAR.to_owned()])]
    keychain_var: Vec<String>,
    /// The tierbridge binary the job runs [default: this one].
    #[arg(long, value_name = "PATH")]
    bin: Option<PathBuf>,
    /// The `tools/` directory with the node snapshot scripts [default: the checkout this binary
    /// was built from].
    #[arg(long, value_name = "DIR")]
    tools_dir: Option<PathBuf>,
    /// Print the plist and the wrapper and what would be done; write nothing, run nothing.
    #[arg(long)]
    dry_run: bool,
    /// Write the files but do not load the job with `launchctl bootstrap`.
    #[arg(long)]
    no_load: bool,
}

#[derive(Args)]
pub struct UninstallArgs {
    /// Print what would be removed; touch nothing.
    #[arg(long)]
    dry_run: bool,
    /// Remove the files but do not `launchctl bootout` the job first.
    #[arg(long)]
    no_unload: bool,
}

struct Paths {
    plist: PathBuf,
    wrapper: PathBuf,
    log_dir: PathBuf,
}

fn paths() -> Result<Paths, Failure> {
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .filter(|h| h.is_absolute())
        .ok_or_else(|| failure("HOME is not set to an absolute path"))?;
    Ok(Paths {
        plist: home.join(format!("Library/LaunchAgents/{LABEL}.plist")),
        wrapper: home.join("Library/Application Support/llm-tierbridge/sync-launchd.sh"),
        log_dir: home.join("Library/Logs/llm-tierbridge"),
    })
}

/// `'...'` for a POSIX shell.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// A name `export` accepts, so nothing else can ride along into the shell script.
fn valid_var(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

struct Job<'a> {
    bin: &'a Path,
    data_repo: &'a Path,
    tools_dir: &'a Path,
    node: Option<&'a Path>,
    keychain_vars: &'a [String],
}

/// The wrapper the plist runs. It prints no secret and tolerates a missing Keychain item (omp
/// discovery then fails and the run fails loud, which is the visible outcome we want).
fn wrapper_script(job: &Job<'_>) -> String {
    let mut s = String::new();
    s.push_str("#!/bin/sh\n");
    s.push_str("# llm-tierbridge daily sync. Generated by `tierbridge sync install-launchd`: re-run that to change it.\n");
    s.push_str("# launchd jobs inherit no environment: PATH is set here and secrets come from the Keychain\n");
    let _ = writeln!(
        s,
        "# (`security add-generic-password -s {KEYCHAIN_SERVICE} -a <VAR> -w`, prompts for the value)."
    );
    let _ = writeln!(s, "PATH={}", sh_quote(JOB_PATH));
    s.push_str("export PATH\n");
    if let Some(node) = job.node {
        let _ = writeln!(
            s,
            "TIERBRIDGE_NODE={}",
            sh_quote(&node.display().to_string())
        );
        s.push_str("export TIERBRIDGE_NODE\n");
    }
    s.push_str("load_keychain() {\n");
    let _ = writeln!(
        s,
        "  value=$(\"${{TIERBRIDGE_SECURITY:-/usr/bin/security}}\" find-generic-password -s {KEYCHAIN_SERVICE} -a \"$1\" -w 2>/dev/null) || {{"
    );
    let _ = writeln!(
        s,
        "    echo \"warning: no Keychain item {KEYCHAIN_SERVICE}/$1; omp discovery may fail\" >&2"
    );
    s.push_str("    return 0\n  }\n  export \"$1=$value\"\n}\n");
    for var in job.keychain_vars {
        let _ = writeln!(s, "load_keychain {}", sh_quote(var));
    }
    let _ = writeln!(
        s,
        "exec {} sync run --data-repo {} --tools-dir {}",
        sh_quote(&job.bin.display().to_string()),
        sh_quote(&job.data_repo.display().to_string()),
        sh_quote(&job.tools_dir.display().to_string())
    );
    s
}

fn plist(wrapper: &Path, log_dir: &Path, hour: u8, minute: u8) -> String {
    let string = |s: &str| format!("<string>{}</string>", xml_escape(s));
    let out = log_dir.join("sync.out.log");
    let err = log_dir.join("sync.err.log");
    let mut s = String::new();
    s.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    s.push_str("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n");
    s.push_str("<plist version=\"1.0\">\n<dict>\n");
    let _ = writeln!(s, "  <key>Label</key>\n  {}", string(LABEL));
    let _ = writeln!(
        s,
        "  <key>ProgramArguments</key>\n  <array>\n    {}\n    {}\n  </array>",
        string("/bin/sh"),
        string(&wrapper.display().to_string())
    );
    let _ = writeln!(
        s,
        "  <key>StartCalendarInterval</key>\n  <dict>\n    <key>Hour</key>\n    <integer>{hour}</integer>\n    <key>Minute</key>\n    <integer>{minute}</integer>\n  </dict>"
    );
    let _ = writeln!(
        s,
        "  <key>StandardOutPath</key>\n  {}",
        string(&out.display().to_string())
    );
    let _ = writeln!(
        s,
        "  <key>StandardErrorPath</key>\n  {}",
        string(&err.display().to_string())
    );
    s.push_str("  <key>RunAtLoad</key>\n  <false/>\n  <key>ProcessType</key>\n  <string>Background</string>\n");
    s.push_str("</dict>\n</plist>\n");
    s
}

/// `node` as the job will find it: `$TIERBRIDGE_NODE`, else the first `node` on this PATH.
fn find_node() -> Option<PathBuf> {
    if let Some(p) = std::env::var_os("TIERBRIDGE_NODE").map(PathBuf::from) {
        return Some(p);
    }
    std::env::split_paths(&std::env::var_os("PATH")?)
        .map(|d| d.join("node"))
        .find(|p| p.is_file())
}

fn absolute(path: &Path) -> Result<PathBuf, Failure> {
    std::path::absolute(path).map_err(|e| failure(format!("{}: {e}", path.display())))
}

fn uid() -> Result<String, Failure> {
    let out = Command::new("id")
        .arg("-u")
        .output()
        .map_err(|e| failure(format!("could not run id: {e}")))?;
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_owned())
}

fn launchctl(args: &[&str]) -> Result<(), Failure> {
    let out = Command::new("launchctl")
        .args(args)
        .output()
        .map_err(|e| failure(format!("could not run launchctl: {e}")))?;
    if out.status.success() {
        Ok(())
    } else {
        Err(failure(format!(
            "launchctl {} failed ({}): {}",
            args.first().copied().unwrap_or(""),
            out.status,
            super::git::first_lines(&out.stderr, 2)
        )))
    }
}

fn write_file(path: &Path, text: &str, mode: u32) -> Result<(), Failure> {
    use std::os::unix::fs::PermissionsExt as _;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| failure(format!("cannot create {}: {e}", parent.display())))?;
    }
    fs::write(path, text).map_err(|e| failure(format!("cannot write {}: {e}", path.display())))?;
    fs::set_permissions(path, fs::Permissions::from_mode(mode))
        .map_err(|e| failure(format!("cannot chmod {}: {e}", path.display())))
}

pub fn install(args: &InstallArgs) -> Result<(), Failure> {
    for var in &args.keychain_var {
        if !valid_var(var) {
            return Err(failure(format!(
                "--keychain-var `{var}` is not a variable name"
            )));
        }
    }
    let paths = paths()?;
    let data_repo = absolute(&args.data_repo)?;
    if !args.dry_run && !data_repo.join(STATE_FILE).is_file() {
        return Err(failure(format!(
            "{}: not a data repo (run `tierbridge sync init --data-repo ...` first)",
            data_repo.display()
        )));
    }
    let bin = match &args.bin {
        Some(b) => absolute(b)?,
        None => std::env::current_exe().map_err(|e| failure(format!("current exe: {e}")))?,
    };
    let tools_dir = {
        let t = fetch::tools_dir(args.tools_dir.as_deref());
        fs::canonicalize(&t).unwrap_or(absolute(&t)?)
    };
    let node = find_node();
    let wrapper = wrapper_script(&Job {
        bin: &bin,
        data_repo: &data_repo,
        tools_dir: &tools_dir,
        node: node.as_deref(),
        keychain_vars: &args.keychain_var,
    });
    let plist = plist(&paths.wrapper, &paths.log_dir, args.hour, args.minute);

    if args.dry_run {
        println!("dry run: nothing is written or loaded\n");
        println!("# {}\n{plist}", paths.plist.display());
        println!("# {}\n{wrapper}", paths.wrapper.display());
        println!("logs: {}/sync.{{out,err}}.log", paths.log_dir.display());
        if !args.no_load {
            println!(
                "would run: launchctl bootstrap gui/$(id -u) {}",
                paths.plist.display()
            );
        }
        return Ok(());
    }
    fs::create_dir_all(&paths.log_dir)
        .map_err(|e| failure(format!("cannot create {}: {e}", paths.log_dir.display())))?;
    write_file(&paths.wrapper, &wrapper, 0o700)?;
    write_file(&paths.plist, &plist, 0o644)?;
    println!("wrote {}", paths.wrapper.display());
    println!("wrote {}", paths.plist.display());
    if args.no_load {
        println!(
            "not loaded (--no-load): `launchctl bootstrap gui/$(id -u) {}`",
            paths.plist.display()
        );
        return Ok(());
    }
    let domain = format!("gui/{}", uid()?);
    // Re-installing replaces a loaded job; "not loaded" is not an error here.
    let _ = launchctl(&["bootout", &format!("{domain}/{LABEL}")]);
    launchctl(&["bootstrap", &domain, &paths.plist.display().to_string()])?;
    println!(
        "loaded {LABEL}: daily at {:02}:{:02}",
        args.hour, args.minute
    );
    Ok(())
}

pub fn uninstall(args: &UninstallArgs) -> Result<(), Failure> {
    let paths = paths()?;
    let present: Vec<&PathBuf> = [&paths.plist, &paths.wrapper]
        .into_iter()
        .filter(|p| p.exists())
        .collect();
    if args.dry_run {
        println!("dry run: nothing is removed or unloaded");
        if !args.no_unload {
            println!("would run: launchctl bootout gui/$(id -u)/{LABEL}");
        }
        for p in [&paths.plist, &paths.wrapper] {
            let what = if p.exists() { "would remove" } else { "absent" };
            println!("{what} {}", p.display());
        }
        return Ok(());
    }
    if !args.no_unload && paths.plist.exists() {
        match launchctl(&["bootout", &format!("gui/{}/{LABEL}", uid()?)]) {
            Ok(()) => println!("unloaded {LABEL}"),
            Err(e) => println!("not unloaded ({})", e.message),
        }
    }
    for p in &present {
        fs::remove_file(p).map_err(|e| failure(format!("cannot remove {}: {e}", p.display())))?;
        println!("removed {}", p.display());
    }
    if present.is_empty() {
        println!("nothing installed");
    }
    println!("logs kept in {}", paths.log_dir.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting_survives_apostrophes_and_spaces() {
        assert_eq!(sh_quote("a b"), "'a b'");
        assert_eq!(sh_quote("it's"), r"'it'\''s'");
        assert_eq!(xml_escape("a&b<c>"), "a&amp;b&lt;c&gt;");
    }

    #[test]
    fn only_plain_variable_names_are_accepted() {
        for ok in ["EASYCLIPROXY_API_KEY", "_x", "A1"] {
            assert!(valid_var(ok), "{ok}");
        }
        for bad in ["", "1A", "A B", "A;rm", "A=B", "$X", "A-B"] {
            assert!(!valid_var(bad), "{bad}");
        }
    }

    #[test]
    fn plist_schedules_a_daily_run_of_the_wrapper() {
        let p = plist(
            Path::new("/h/Library/Application Support/llm-tierbridge/sync-launchd.sh"),
            Path::new("/h/Library/Logs/llm-tierbridge"),
            6,
            30,
        );
        assert!(p.contains("<string>dev.blyzer.llm-tierbridge.sync</string>"));
        assert!(p.contains("<key>Hour</key>\n    <integer>6</integer>"));
        assert!(p.contains("<key>Minute</key>\n    <integer>30</integer>"));
        assert!(p.contains("<string>/bin/sh</string>"));
        assert!(p.contains("/h/Library/Logs/llm-tierbridge/sync.err.log"));
        assert!(p.contains("<key>RunAtLoad</key>\n  <false/>"));
    }
}
